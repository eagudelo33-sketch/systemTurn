CREATE TABLE turno (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fecha DATE NOT NULL,
  numero INT NOT NULL,
  hora_solicitud TIME(0) NOT NULL,
  hora_atencion TIME(0),
  estado VARCHAR(16) NOT NULL CHECK (estado IN ('PENDIENTE', 'ATENDIDO', 'CANCELADO')),
  version BIGINT NOT NULL,
  CONSTRAINT uk_turno_fecha_numero UNIQUE (fecha, numero)
);
